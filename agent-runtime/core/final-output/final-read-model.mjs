export function buildAgentFinalReadModelV1({
  runID,
  taskID,
  sessionID,
  status,
  finalText,
  finalTextSource,
  toolObservations,
  artifactPath,
  now = () => new Date().toISOString(),
  productMutationPolicyForRun,
}) {
  const gate = toolObservations?.cmcFreshnessGate || {};
  return {
    schemaVersion: "agent-final-read-model-v1",
    runID,
    taskID,
    sessionID,
    status,
    finalText,
    finalTextSource,
    outputGuardStatus: toolObservations?.outputGuard?.status || "unknown",
    outputGuardReason: toolObservations?.outputGuard?.reason || null,
    cmcGateSummary: {
      status: gate.status || "unknown",
      provider: gate.provider || null,
      freshness: gate.freshness || null,
      transportStatus: gate.transportStatus || null,
      skillHubDisplay: gate.skillHubDisplay || null,
      skillHubDisplayStatus: gate.skillHubDisplayStatus || null,
      allowSkillHubResultDisplay: Boolean(gate.allowSkillHubResultDisplay),
      displayableResultText: gate.displayableResultText || null,
      displayableResultSource: gate.displayableResultSource || null,
      parserEvidenceStatus: gate.parserEvidenceStatus || null,
      allowSkillHubReturnedPrices: Boolean(gate.allowSkillHubReturnedPrices),
      skillHubReturnedPriceTokenCount: Number(gate.skillHubReturnedPriceTokenCount || 0),
      skillHubReturnedTextSource: gate.skillHubReturnedTextSource || null,
      skillHubReturnedTextCharCount: Number(gate.skillHubReturnedTextCharCount || 0),
      researchEvidence: gate.researchEvidence || null,
      researchEvidenceStatus: gate.researchEvidenceStatus || null,
      readableEvidenceCount: Number(gate.readableEvidenceCount || 0),
      emptyEvidenceReason: gate.emptyEvidenceReason || null,
      priceSnapshot: gate.priceSnapshot || null,
      priceSnapshotStatus: gate.priceSnapshotStatus || null,
      assetCount: Number(gate.assetCount || 0),
      allowResearchConclusion: Boolean(gate.allowResearchConclusion),
      allowConcretePrices: Boolean(gate.allowConcretePrices),
      reason: gate.reason || null,
    },
    marketsGateSummary: toolObservations?.marketsResearch?.gate || null,
    productMutationPolicy: productMutationPolicyForRun(toolObservations),
    generatedAt: now(),
    artifactPath,
  };
}
